from __future__ import annotations

import json
import os
import re
from pathlib import Path
from threading import RLock
from typing import Any

from .schemas import AppConfig


PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_ROOT = Path(os.getenv("SENSORLAB_DATA_DIR", PROJECT_ROOT / "data")).resolve()


class FileStore:
    """Small transparent file store suitable for a classroom project."""

    def __init__(self, root: Path = DATA_ROOT) -> None:
        self.root = root
        self.datasets_dir = root / "datasets"
        self.models_dir = root / "models"
        self.events_path = root / "actuator-events.jsonl"
        self.config_path = root / "config.json"
        self._lock = RLock()

    def ensure(self) -> None:
        self.datasets_dir.mkdir(parents=True, exist_ok=True)
        self.models_dir.mkdir(parents=True, exist_ok=True)

    def load_json(self, path: Path, default: Any = None) -> Any:
        if not path.exists():
            return default
        with self._lock, path.open("r", encoding="utf-8") as handle:
            return json.load(handle)

    def save_json(self, path: Path, value: Any) -> None:
        self.ensure()
        temp_path = path.with_suffix(path.suffix + ".tmp")
        with self._lock, temp_path.open("w", encoding="utf-8") as handle:
            json.dump(value, handle, ensure_ascii=False, indent=2, default=str)
        temp_path.replace(path)

    def append_jsonl(self, path: Path, value: Any) -> None:
        self.ensure()
        with self._lock, path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(value, ensure_ascii=False, default=str) + "\n")

    def read_jsonl(self, path: Path, limit: int = 100) -> list[dict[str, Any]]:
        if not path.exists():
            return []
        with self._lock, path.open("r", encoding="utf-8") as handle:
            lines = handle.readlines()[-limit:]
        return [json.loads(line) for line in reversed(lines) if line.strip()]


class ConfigRepository:
    def __init__(self, store: FileStore) -> None:
        self.store = store
        self._config: AppConfig | None = None
        self._lock = RLock()

    def get(self) -> AppConfig:
        with self._lock:
            if self._config is None:
                raw = self.store.load_json(self.store.config_path)
                self._config = AppConfig.model_validate(raw) if raw else AppConfig()
                if raw is None:
                    self.save(self._config)
            return self._config.model_copy(deep=True)

    def save(self, config: AppConfig) -> AppConfig:
        with self._lock:
            self._config = config.model_copy(deep=True)
            self.store.save_json(self.store.config_path, self._config.model_dump(mode="json"))
            return self._config.model_copy(deep=True)


def safe_stem(value: str, fallback: str = "dataset") -> str:
    stem = Path(value).stem.strip().lower()
    stem = re.sub(r"[^a-z0-9_-]+", "-", stem).strip("-")
    return stem[:60] or fallback


def is_safe_identifier(value: str) -> bool:
    """Allow only the identifiers generated by this application in file paths."""
    return bool(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,127}", value))
